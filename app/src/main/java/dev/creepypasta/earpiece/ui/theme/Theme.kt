/**
 * App theme.
 *
 * Dynamic colour needs Android 12 (API 31); below that the hand-tuned palette
 * above is used. The system bars are made transparent by `enableEdgeToEdge()`
 * in the activity, so all this has to do is tell the platform whether the
 * status/navigation bar icons should be drawn light or dark.
 */
@Composable
fun EarpieceTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColors
        else -> LightColors
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            // The composition's context is the activity in every real run, but a
            // preview or a hosted composition may not be; skip rather than crash.
            val window = context.findActivity()?.window ?: return@SideEffect
            val controller: WindowInsetsControllerCompat = WindowCompat.getInsetsController(window, view)
            // Dark scheme -> light icons; light scheme -> dark icons.
            controller.isAppearanceLightStatusBars = !darkTheme
            controller.isAppearanceLightNavigationBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = EarpieceTypography,
        content = content,
    )
}

/**
 * Walks the context wrapper chain to the hosting activity. Returns null in
 * previews and in any composition whose context is not activity-backed.
 */
private fun Context.findActivity(): Activity? {
    var current: Context? = this
    while (current is ContextWrapper) {
        if (current is Activity) return current
        current = current.baseContext
    }
    return current as? Activity
}
